// Bakes the Kirkify reference faces into a module the Convex action can
// import. Convex functions can't read files at runtime, and a hosted URL would
// put the provider's fetcher (and its allowlist) between us and the model,
// see resolveImageReferences in convex/inference/image.ts. The JPEGs are
// small enough that a base64 module is the boring, reliable answer.
//
//   bun scripts/embed-kirkify-references.mjs
//
// Sources: scripts/kirkify-sources/face-*.jpg, tight face crops upscaled to
// ~900px. The model resizes what it's given, so a face filling the frame
// keeps far more of its detail than the same face in a wider portrait; the
// crops measurably improved the likeness over the full photos the page shows
// (apps/v2/public/kirkify). Output: convex/kirkify/references.ts. Rerun after
// changing a crop.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sourceDir = resolve(here, "kirkify-sources");
const outFile = resolve(here, "../convex/kirkify/references.ts");

const files = readdirSync(sourceDir)
  .filter((name) => /^face-\d+\.jpe?g$/i.test(name))
  .sort();
if (files.length === 0) {
  throw new Error(`no face-*.jpg files in ${sourceDir}`);
}

const entries = files.map((name) => {
  const base64 = readFileSync(join(sourceDir, name)).toString("base64");
  return [
    "  {",
    `    name: ${JSON.stringify(name)},`,
    `    url: "data:image/jpeg;base64,${base64}",`,
    "  },",
  ].join("\n");
});

const banner = [
  "// Generated by scripts/embed-kirkify-references.mjs from",
  "// scripts/kirkify-sources/face-*.jpg. Don't edit by hand; rerun the script",
  "// after changing a crop.",
  "",
  'import type { ImageInputReference } from "../inference/image";',
  "",
  "export const KIRKIFY_REFERENCES: readonly ImageInputReference[] = [",
];

writeFileSync(outFile, [...banner, ...entries, "];", ""].join("\n"));
console.log(`wrote ${files.length} references to ${outFile}`);
